/**
 * The proxy's own login page.
 *
 * Deliberately a server-rendered, self-contained HTML document with no
 * dependency on DSH's asset pipeline: the visitor is unauthenticated, so the app
 * bundle is exactly what must NOT be reachable yet. One document, one inline
 * stylesheet, one form, and — only when third-party channels exist — one small
 * inline script. A password-only deployment stays 100% script-free.
 *
 * Security properties, all enforced elsewhere but relied on here:
 * - the form posts to the proxy's own path with `autocomplete` off for the
 *   username and `current-password` for the password, so a password manager can
 *   fill it without the page ever reading the value;
 * - the response is marked `no-store` and `no-referrer` by the caller, so a
 *   credential-bearing POST is not cached or leaked through a Referer;
 * - the page states the transport it is on: served over cleartext HTTP (no TLS
 *   in front) the caller refuses to accept the submission at all, because a
 *   password posted in the clear is not worth collecting.
 *
 * Third-party login buttons are `<a>` links with INLINE SVG icons and no
 * external asset; only the channels enabled in the config are rendered. With
 * no password configured the local form is omitted entirely.
 *
 * The STATIC popup script (only when third-party channels exist) opens the
 * authorization flow in a script-owned popup, reports the outcome over a
 * same-origin BroadcastChannel, and lets the visitor cancel. Both cancellation
 * and a three-minute timeout close the popup; on success the opener navigates
 * to `/` (reloading the login path would just re-serve the form). It contains
 * no operator input, no network call and no reference to the app bundle.
 * Without JavaScript the link's `target="_blank"` still opens a separate
 * window, so the current page is never taken over.
 */
import type { OAuthLoginButton } from './oauth/providers.ts'
import { OAUTH_CHANNEL, OAUTH_MESSAGE_SOURCE, OAUTH_POPUP_TIMEOUT_MS } from './contract.ts'

/** Everything the page needs to render; no state is read from the request. */
export interface LoginPageOptions {
  /** Overrides the `<title>`/heading when the deployment names its proxy. */
  title?: string
  /** Human-readable error shown above the form (already localized by the caller). */
  error?: string
  /** Path the form posts to (the login endpoint). */
  action: string
  /** Whether the visitor arrived over TLS (a trusted proxy reported https). */
  secure: boolean
  /** Enabled third-party channels; omitted/empty keeps the original form only. */
  providers?: OAuthLoginButton[]
  /** False hides the local password form when only third-party login is on. */
  passwordForm?: boolean
}

/** HTML-escape a value interpolated into the document. */
function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

/**
 * Render the login document.
 * @param options - title, error, form target, and the enabled OAuth channels.
 * @returns a complete HTML document as a string.
 */
export function renderLoginPage(options: LoginPageOptions): string {
  const title = escapeHtml(options.title ?? 'DSH 局域网代理')
  const action = escapeHtml(options.action)
  const error = options.error === undefined || options.error === ''
    ? ''
    : `<p class="error" role="alert">${escapeHtml(options.error)}</p>`
  const insecure = options.secure
    ? ''
    : '<p class="warn" role="alert">当前连接未加密（HTTP）：密码会以明文经过网络，请让反向代理启用 HTTPS 后再登录。</p>'
  const passwordForm = options.passwordForm !== false
  const providers = options.providers ?? []
  const subtitle = passwordForm
    ? '请输入用户名和密码以访问 DSH。'
    : '请使用已启用的第三方账号登录。'
  const form = passwordForm ? `
  <form method="post" action="${action}" autocomplete="on">
    <label for="username">用户名</label>
    <input id="username" name="username" type="text" autocomplete="username" autocapitalize="none" autocorrect="off" spellcheck="false" required autofocus>
    <label for="password">密码</label>
    <input id="password" name="password" type="password" autocomplete="current-password" required>
    <button type="submit">登录</button>
  </form>` : ''
  // `icon` is generated by providers.ts (never user input); labels are escaped.
  const oauth = providers.length === 0 ? '' : `
  <p id="oauth-error" class="error" role="alert" hidden></p>
  <p id="oauth-pending" class="pending" role="status" hidden>
    正在等待第三方认证…
    <button type="button" id="oauth-cancel" class="cancelBtn">取消认证</button>
  </p>
  <div class="oauth">
    ${passwordForm ? '<p class="sub oauthHint">或使用第三方账号登录</p>' : ''}
    ${providers.map(button => `<a class="oauthBtn" href="${escapeHtml(button.startUrl)}" target="_blank" rel="noopener noreferrer" onclick="return window.dshProxyOauthOpen ? window.dshProxyOauthOpen(this) : true">${button.icon}<span>${escapeHtml(button.label)}</span></a>`).join('\n    ')}
  </div>`
  // Static script, present only when third-party channels are enabled. All
  // interpolated values are module constants; no config data reaches JS source.
  const oauthScript = providers.length === 0 ? '' : `
<script>
(function () {
  var popup = null;
  var timeout = null;
  var watcher = null;
  // Only a live flow may react to a result. Authorization can finish in the
  // popup just as the visitor cancels / times out / closes it; that late
  // message must not navigate the opener afterwards.
  var active = false;
  function showError(text) {
    var box = document.getElementById('oauth-error');
    if (box) { box.textContent = text; box.removeAttribute('hidden'); }
  }
  function setPending(on) {
    var box = document.getElementById('oauth-pending');
    if (box) box.hidden = !on;
  }
  function cleanup() {
    if (timeout !== null) { window.clearTimeout(timeout); timeout = null; }
    if (watcher !== null) { window.clearInterval(watcher); watcher = null; }
    active = false;
    popup = null;
    setPending(false);
  }
  function closePopup() {
    if (popup !== null && !popup.closed) { try { popup.close(); } catch (error) {} }
  }
  function receive(data) {
    if (!active) return;
    if (!data || data.source !== ${JSON.stringify(OAUTH_MESSAGE_SOURCE)} || data.intent !== 'login') return;
    cleanup();
    if (data.status === 'ok') { window.location.replace('/'); return; }
    showError(data.message || '第三方登录未完成，请重试。');
  }
  window.dshProxyOauthOpen = function (anchor) {
    try { popup = window.open('about:blank', 'dsh-proxy-oauth', 'popup,width=520,height=700'); } catch (error) { popup = null; }
    if (popup === null) return true;
    try { popup.opener = null; } catch (error) {}
    try { popup.location.href = anchor.href; } catch (error) {}
    var errorBox = document.getElementById('oauth-error');
    if (errorBox) errorBox.setAttribute('hidden', '');
    active = true;
    setPending(true);
    timeout = window.setTimeout(function () {
      closePopup();
      cleanup();
      showError('等待第三方认证超时（3 分钟），弹窗已关闭，请重试。');
    }, ${OAUTH_POPUP_TIMEOUT_MS});
    watcher = window.setInterval(function () {
      if (popup !== null && popup.closed) cleanup();
    }, 1000);
    return false;
  };
  window.dshProxyOauthCancel = function () {
    closePopup();
    cleanup();
    showError('已取消第三方认证。');
  };
  var cancel = document.getElementById('oauth-cancel');
  if (cancel) cancel.addEventListener('click', window.dshProxyOauthCancel);
  try {
    var channel = new BroadcastChannel(${JSON.stringify(OAUTH_CHANNEL)});
    channel.onmessage = function (event) { receive(event.data); };
  } catch (error) {}
  window.addEventListener('message', function (event) {
    if (event.origin !== window.location.origin) return;
    receive(event.data);
  });
})();
</script>`

  return `<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="referrer" content="no-referrer">
<meta name="robots" content="noindex, nofollow">
<title>${title}</title>
<style>
:root { color-scheme: light dark; }
* { box-sizing: border-box; }
body {
  margin: 0; min-height: 100vh; display: grid; place-items: center;
  background: #0f1115; color: #e6edf3;
  font: 14px/22px -apple-system, BlinkMacSystemFont, "Segoe UI", "PingFang SC", "Microsoft YaHei", sans-serif;
}
main { width: min(360px, calc(100vw - 32px)); padding: 24px; border: 1px solid #30363d; border-radius: 12px; background: #161b22; }
h1 { margin: 0 0 4px; font-size: 18px; line-height: 26px; }
p.sub { margin: 0 0 16px; color: #8b949e; font-size: 12px; line-height: 18px; }
label { display: block; margin: 0 0 4px; color: #c9d1d9; font-size: 13px; }
input {
  width: 100%; margin: 0 0 12px; padding: 8px 10px;
  border: 1px solid #30363d; border-radius: 8px; background: #0d1117; color: #e6edf3;
  font: inherit;
}
input:focus-visible { outline: 2px solid #2f81f7; outline-offset: 1px; }
button {
  width: 100%; padding: 8px 14px; border: 1px solid #2f81f7; border-radius: 8px;
  background: #2f81f7; color: #fff; font: inherit; font-weight: 500; cursor: pointer;
}
button:hover { background: #388bfd; border-color: #388bfd; }
p.error { margin: 0 0 12px; padding: 8px 10px; border-left: 3px solid #f85149; border-radius: 4px; background: rgb(248 81 73 / 12%); color: #ff7b72; font-size: 13px; }
p.error[hidden] { display: none; }
p.pending[hidden] { display: none; }
p.pending { margin: 12px 0 0; padding: 8px 10px; border-left: 3px solid #2f81f7; border-radius: 4px; background: rgb(47 129 247 / 12%); color: #79c0ff; font-size: 12px; line-height: 18px; }
button.cancelBtn { width: auto; margin: 8px 0 0; padding: 4px 10px; font-size: 12px; }
p.warn { margin: 12px 0 0; padding: 8px 10px; border-left: 3px solid #d29922; border-radius: 4px; background: rgb(210 153 34 / 12%); color: #d29922; font-size: 12px; line-height: 18px; }
div.oauth { display: grid; gap: 8px; margin-top: 4px; }
p.oauthHint { margin: 12px 0 0; text-align: center; }
a.oauthBtn {
  display: flex; align-items: center; justify-content: center; gap: 8px;
  box-sizing: border-box; width: 100%; padding: 8px 12px;
  border: 1px solid #30363d; border-radius: 8px; background: #0d1117; color: #e6edf3;
  font-size: 13px; line-height: 20px; text-decoration: none; cursor: pointer;
}
a.oauthBtn:hover { border-color: #2f81f7; }
a.oauthBtn svg { flex: none; }
@media (prefers-color-scheme: light) {
  body { background: #f6f7f9; color: #0f1115; }
  main { background: #fff; border-color: #d7dbe0; }
  p.sub { color: #61666b; }
  label { color: #3c4149; }
  input { background: #fff; border-color: #d7dbe0; color: #0f1115; }
  a.oauthBtn { background: #fff; border-color: #d7dbe0; color: #0f1115; }
  p.error { color: #b3261e; }
  p.pending { color: #0969da; }
}
</style>
</head>
<body>
<main>
  <h1>${title}</h1>
  <p class="sub">${subtitle}</p>
  ${error}
  ${insecure}
  ${form}
  ${oauth}
</main>
${oauthScript}
</body>
</html>
`
}

/** Localized failure copy for the login page, keyed by the auth core's reason. */
export function loginFailureMessage(
  reason: 'invalid' | 'locked' | 'disabled',
  retryAfterMs: number,
): string {
  if (reason === 'locked') {
    const minutes = Math.max(1, Math.ceil(retryAfterMs / 60000))
    return `失败次数过多，请在约 ${minutes} 分钟后重试。`
  }
  if (reason === 'disabled') return '管理员尚未设置密码，无法登录。'
  // One message for a wrong username and a wrong password: nothing to enumerate.
  return '用户名或密码不正确。'
}
